const LangContext = createContext<{ lang: Lang; t: (key: string) => string; setLang: (l: Lang) => void }>({
  lang: 'en',
  t: (key) => key,
  setLang: () => {},
})

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(
    () => (localStorage.getItem('icle-lang') as Lang) || 'zh',
  )
  const setLang = (next: Lang) => {
    localStorage.setItem('icle-lang', next)
    setLangState(next)
  }
  const t = (key: string) => DICTS[lang][key] ?? key
  return <LangContext.Provider value={{ lang, t, setLang }}>{children}</LangContext.Provider>
}

export function useLang() {
  return useContext(LangContext)
}
